"""LED map for firmware: each LED's index in the data chain, and what it sits under.

Run with KiCad's bundled Python after tools/gen_pcb.py:

    /Applications/KiCad/KiCad.app/Contents/Frameworks/Python.framework/Versions/Current/bin/python3 tools/led_map.py [board]

Walks the chain on the board itself, from LED_DIN through every DOUT -> DIN, so the table
matches the copper. Writes docs/led-map.csv and docs/led-map.md. The chain index is
0-based, as ZMK and QMK count pixels.
"""
import csv
import re
import sys
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parent.parent


def pin(fp, fn):
    """DIN/DOUT pad of an LED: SK6812MINI-E (per key) 2/4, SK6812MINI (underglow) 3/1."""
    mini_e = "MINI-E" in fp.GetFPIDAsString()
    num = {"DIN": "2", "DOUT": "4"}[fn] if mini_e else {"DIN": "3", "DOUT": "1"}[fn]
    return fp.FindPadByNumber(num).GetNetname()


def build(board_path):
    b = pcbnew.LoadBoard(str(board_path))
    fps = list(b.GetFootprints())
    leds = {f.GetReference(): f for f in fps if re.fullmatch(r"LED\d+", f.GetReference())}
    sw_by_key = {f.GetFieldText("Key"): f for f in fps
                 if re.fullmatch(r"SW\d+", f.GetReference()) and f.HasField("Key") and f.GetFieldText("Key")}
    d_by_key = {f.GetFieldText("Key"): f for f in fps
                if re.fullmatch(r"D\d+", f.GetReference()) and f.HasField("Key") and f.GetFieldText("Key")}
    din = {pin(f, "DIN"): r for r, f in leds.items()}
    cur = next(r for r, f in leds.items() if pin(f, "DIN") == "LED_DIN")
    chain = []
    while cur and cur not in chain:
        chain.append(cur)
        cur = din.get(pin(leds[cur], "DOUT"))
    if len(chain) != len(leds):
        sys.exit(f"the chain reaches {len(chain)} of {len(leds)} LEDs")
    rows = []
    for i, ref in enumerate(chain):
        fp = leds[ref]
        key = fp.GetFieldText("Key") if fp.HasField("Key") else ""
        side, name = key.split()
        if name.startswith("UG"):
            what, spot, row, col, sw = "underglow", f"{side} G{name[2:]}", "", "", ""
        else:
            what, spot = "key", f"{side} {name}"
            s, d = sw_by_key[key], d_by_key[key]
            col = s.FindPadByNumber("1").GetNetname().split("/")[-1].replace("COL", "")
            row = d.FindPadByNumber("1").GetNetname().split("/")[-1].replace("ROW", "")
            sw = s.GetReference()
        kind = "outer pinky (breaks off)" if what == "key" and name[0] == "K" and name[2] == "0" else ""
        rows.append(dict(index=i, ref=ref, led=spot, type=what, side="left" if side == "L" else "right",
                         switch=sw, matrix_row=row, matrix_col=col, note=kind))
    return rows


def write(rows):
    out = ROOT / "docs"
    out.mkdir(exist_ok=True)
    with open(out / "led-map.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    lines = [
        "# LED map",
        "",
        "Generated by `tools/led_map.py` from the board, by walking the data chain from `LED_DIN`.",
        "**Index** is the LED's position in the chain, 0-based (the pixel number ZMK and QMK use).",
        "**LED** names the spot: `L K12` is the LED under the left key in row 1, column 2 of that half's",
        "grid (thumbs `L T0`..`L T2`); `L G3` is left underglow spot 3. **Matrix** is the key's",
        "row and column in the wired 6 x 7 matrix (left half rows 0-2, right half rows 3-5).",
        "",
        "| Index | Ref | LED | Type | Switch | Matrix row | Matrix col | Note |",
        "|---:|---|---|---|---|---:|---:|---|",
    ]
    for r in rows:
        lines.append(f"| {r['index']} | {r['ref']} | {r['led']} | {r['type']} | {r['switch']} | "
                     f"{r['matrix_row']} | {r['matrix_col']} | {r['note']} |")
    lines += ["", f"{len(rows)} LEDs. The outer pinky LEDs are last, so on the 36-key build the chain ends at "
              f"index {min(r['index'] for r in rows if r['note']) - 1}."]
    (out / "led-map.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    board = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "unicorne.kicad_pcb"
    rows = build(board)
    write(rows)
    print(f"docs/led-map.csv, docs/led-map.md: {len(rows)} LEDs")
